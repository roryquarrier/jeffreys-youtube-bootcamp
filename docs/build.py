#!/usr/bin/env python3
"""Build content.js for Jeffrey's YouTube Bootcamp site.

Reads the markdown in ../course/ (and ../README.md for the overview) and emits a
single content.js holding every section as pre-rendered HTML. The site is fully
static: no runtime markdown parsing, no CDN, no build step needed to serve it.

Re-run after editing the markdown:

    cd docs && python3 build.py
"""
import json
import os
import re

import markdown

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# (id, path relative to repo root, nav label, group, emoji, blurb)
SECTIONS = [
    ("overview", "README.md", "Start Here", "Start", "\U0001F534",
     "What the job actually is, and your five 20-minute steps."),
    ("dashboard", None, "My Progress", "Start", "\U0001F4C8",
     "Your stars and quiz scores - saved in this browser."),
    ("step-01", "course/01-understand.md", "1. Understand the Job", "The 20 Minutes", "\U0001F50D",
     "What a YouTuber really is - and why most channels quit."),
    ("step-02", "course/02-plan.md", "2. Plan Your Channel", "The 20 Minutes", "\U0001F5FA\uFE0F",
     "Niche, name, and your first 10 videos."),
    ("step-03", "course/03-make-video.md", "3. Make Your First Video", "The 20 Minutes", "\U0001F3AC",
     "The script formula: hook, body, payoff."),
    ("step-04", "course/04-upload.md", "4. Upload Like a Pro", "The 20 Minutes", "\U0001F680",
     "Titles, thumbnails, CTR and retention."),
    ("step-05", "course/05-grow-safe.md", "5. Grow & Stay Safe", "The 20 Minutes", "\U0001F4C8",
     "The rules that compound - and the rules that protect you."),
    ("example", "course/06-rivals-example.md", "Rivals Example", "Reference", "\U0001F3AE",
     "The whole course applied to a Rivals channel, start to finish."),
    ("script", "course/07-script-template.md", "Script Template", "Reference", "\u270F\uFE0F",
     "Copy this before every video."),
    ("toolkit", "course/08-toolkit.md", "Free Toolkit", "Reference", "\U0001F9F0",
     "OBS, CapCut, Canva - everything you need, $0."),
    ("grownups", "course/09-grownups.md", "For Grown-Ups", "Reference", "\U0001F9D1\u200D\U0001F3EB",
     "Account rules, safety settings, copyright, realistic expectations."),
]

EXTENSIONS = ["tables", "fenced_code", "sane_lists", "attr_list", "md_in_html"]

GROUP_EMOJI = {"Start": "\U0001F3C1", "The 20 Minutes": "\u23F1\uFE0F", "Reference": "\U0001F5C2\uFE0F"}


def first_heading(text, fallback):
    m = re.search(r"^#\s+(.+)$", text, re.M)
    return m.group(1).strip() if m else fallback


def build():
    quiz_path = os.path.join(ROOT, "course", "quizzes.json")
    quizzes = {}
    if os.path.exists(quiz_path):
        with open(quiz_path, encoding="utf-8") as f:
            quizzes = {k: v for k, v in json.load(f).items() if not k.startswith("_")}

    out = []
    for sid, rel, label, group, emoji, blurb in SECTIONS:
        if rel is None:
            raw, html, kind = "", "", "dashboard"
        else:
            with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
                raw = f.read()
            # The leading H1 becomes the page title, so drop it from the body.
            body = re.sub(r"^#\s+.+\n", "", raw, count=1)
            html, kind = markdown.markdown(body, extensions=EXTENSIONS), "doc"
        out.append({
            "id": sid,
            "label": label,
            "title": first_heading(raw, label),
            "group": group,
            "groupEmoji": GROUP_EMOJI.get(group, "\u2022"),
            "emoji": emoji,
            "blurb": blurb,
            "kind": kind,
            "quiz": quizzes.get(sid),
            "html": html,
        })
    payload = json.dumps({"sections": out}, ensure_ascii=False, separators=(",", ":"))
    js = "/* Generated by build.py - do not edit by hand. */\nwindow.COURSE = " + payload + ";\n"
    dest = os.path.join(HERE, "content.js")
    with open(dest, "w", encoding="utf-8") as f:
        f.write(js)
    print("wrote %s (%s bytes, %d sections)" % (dest, format(len(js), ","), len(out)))


if __name__ == "__main__":
    build()
